import {logSystemEvent} from "@/lib/server/system-log";
import {NextRequest,NextResponse} from "next/server";
import {ZoomApiError,zoomApi,zoomAuthorizedFetchUrl,zoomServiceClient} from "@/lib/server/zoom";
import {classAccessForProfile} from "@/lib/server/zoom-classroom";
import {readRecordingStreamToken} from "@/lib/server/zoom-recording";
export const dynamic="force-dynamic";

export async function GET(request:NextRequest,{params}:{params:Promise<{recordingId:string}>}){
 let stage="token";
 try{
  const {recordingId}=await params;const token=request.nextUrl.searchParams.get("token")||"";
  const grant=readRecordingStreamToken(token);if(grant.recordingId!==recordingId)throw new Error("Recording access token does not match this recording.");
  stage="profile";
  const db=zoomServiceClient();
  const {data:profile,error:profileError}=await db.from("profiles").select("id,role,active,full_name").eq("id",grant.profileId).maybeSingle();
  if(profileError||!profile?.active)return new NextResponse("Recording access is no longer valid.",{status:403});
  stage="recording";
  const {data:recording,error}=await db.from("zoom_recordings").select("id,zoom_meeting_id,zoom_recording_file_id,download_url,status,learner_visible,file_type").eq("id",recordingId).maybeSingle();
  if(error||!recording||recording.status!=="completed"||!recording.download_url)return new NextResponse("Recording is unavailable.",{status:404});
  stage="meeting";
  const {data:meeting,error:meetingError}=await db.from("zoom_meetings").select("id,host_account_id,zoom_meeting_id,zoom_meeting_uuid,schedule_event_id,purpose,learner_recording_visible").eq("id",recording.zoom_meeting_id).maybeSingle();
  if(meetingError||!meeting)return new NextResponse("Recording meeting is unavailable.",{status:404});
  stage="authorization";
  let allowed=profile.role==="admin";
  if(!allowed&&meeting.purpose==="class"&&meeting.schedule_event_id){
   const access=await classAccessForProfile(db,meeting.schedule_event_id,profile as any);
   if(profile.role==="trainer")allowed=Boolean(access?.canHost);
   else if(recording.learner_visible&&meeting.learner_recording_visible)allowed=Boolean(access?.canJoin);
  }
  if(!allowed)return new NextResponse("You do not have access to this recording.",{status:403});
  const range=request.headers.get("range");
  stage="upstream";
  let upstream=await zoomAuthorizedFetchUrl(meeting.host_account_id,recording.download_url,{headers:range?{Range:range}:{}});
  if((upstream.status===401||upstream.status===403)&&meeting.zoom_meeting_id&&recording.zoom_recording_file_id){
   // Recording download URLs are generated by Zoom and can become stale. Resolve a
   // fresh URL with the host's current OAuth token, then retry exactly once.
   stage="refresh-url";
   // Recordings belong to a meeting occurrence, not necessarily its latest numeric meeting ID.
   // Zoom requires double-encoding for UUIDs starting with "/" or containing "//".
   const instance=String(meeting.zoom_meeting_uuid||"").trim();
   if(!instance)throw new Error("Meeting instance UUID unavailable.");
   const instancePath=instance.startsWith("/")||instance.includes("//")
    ?encodeURIComponent(encodeURIComponent(instance)):encodeURIComponent(instance);
   const refreshed=await zoomApi(meeting.host_account_id,`/meetings/${instancePath}/recordings`);
   const file=(Array.isArray(refreshed.recording_files)?refreshed.recording_files:[])
    .find((x:{id?:string|number})=>String(x.id||"")===String(recording.zoom_recording_file_id));
   if(file?.download_url){
    stage="retry-upstream";
    upstream=await zoomAuthorizedFetchUrl(meeting.host_account_id,String(file.download_url),{headers:range?{Range:range}:{}});
    if(upstream.ok||upstream.status===206){
     await db.from("zoom_recordings").update({download_url:String(file.download_url),updated_at:new Date().toISOString()}).eq("id",recordingId);
    }
   }
  }  
  if(!upstream.ok&&upstream.status!==206){const referenceId=await logSystemEvent({source:"zoom-recording",action:"stream",code:"ZOOM_STREAM_HTTP_"+String(upstream.status),message:"Recording upstream delivery failed"});
   console.error("[zoom-recording] upstream response failure",{status:upstream.status,stage,referenceId});return new NextResponse("Unable to stream this Zoom recording. Reference: "+referenceId,{status:502,headers:{"Cache-Control":"no-store"}});}
  // A provider login page or JSON error may be returned with HTTP 200. Sending
  // that as video masks the real failure as a generic browser playback error.
  const mediaType=(upstream.headers.get("content-type")||"").toLowerCase();
  if(mediaType.includes("text/html")||mediaType.includes("application/json")){
   const referenceId=await logSystemEvent({source:"zoom-recording",action:"stream",code:"ZOOM_STREAM_NON_MEDIA",message:"Zoom recording endpoint returned non-media content"});
   console.error("[zoom-recording] unexpected upstream content type",{referenceId,stage});
   return new NextResponse("Unable to stream this Zoom recording. Reference: "+referenceId,{status:502,headers:{"Cache-Control":"no-store"}});
  }
  const headers=new Headers();
  for(const key of ["content-type","content-length","content-range","accept-ranges","etag","last-modified"]){const value=upstream.headers.get(key);if(value)headers.set(key,value);}
  headers.set("Cache-Control","private, no-store");
  headers.set("Content-Disposition","inline");
  return new NextResponse(upstream.body,{status:upstream.status,headers});
 }catch(error){
  const upstreamStatus=error instanceof ZoomApiError?error.status:null;
  const referenceId=await logSystemEvent({source:"zoom-recording",action:"stream",code:"ZOOM_STREAM_"+stage.toUpperCase().replace(/-/g,"_")+(upstreamStatus?"_HTTP_"+upstreamStatus:""),message:"Recording playback could not be established"});
  console.error("[zoom-recording] stream exception",{stage,upstreamStatus,referenceId});
  return new NextResponse("Recording stream unavailable. Reference: "+referenceId,{status:stage==="token"?403:502,headers:{"Cache-Control":"no-store"}});
 }
}
